export type Copy = { [K in keyof typeof en]: string };

const catalogs: Record<UiLanguage, Copy> = { en, zh };

export function uiLanguage(value?: string): UiLanguage {
  return (value ?? '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function detectUiLanguage(nav?: { language?: string; languages?: readonly string[] }): UiLanguage {
  const source = nav ?? (typeof navigator === 'undefined' ? undefined : navigator);
  const preferred = source?.languages?.[0] ?? source?.language ?? 'en';
  return uiLanguage(preferred);
}

export function languageFromApi(api: { i18n?: { getUILanguage?: () => string } } = {}): UiLanguage {
  const preferred = api.i18n?.getUILanguage?.();
  if (preferred) return uiLanguage(preferred);
  return detectUiLanguage();
}

export function copyFor(language: UiLanguage = 'en'): Copy {
  return catalogs[language];
}

export function notificationCopy(language: UiLanguage = 'en') {
  const text = copyFor(language);
  return {
    savedTitle: text.notifSavedTitle,
    savedMessage: text.notifSavedMessage,
    existingTitle: text.notifExistingTitle,
    existingMessage: text.notifExistingMessage,
    unsavableTitle: text.notifUnsavableTitle,
    unsavableMessage: text.notifUnsavableMessage,
    failedTitle: text.notifFailedTitle,
    failedMessage: text.notifFailedMessage,
    actionTitles: {
      'open-library': text.notifOpenLibrary,
      undo: text.notifUndo,
      'open-existing': text.notifOpen,
      'update-existing': text.notifUpdate,
      'copy-existing': text.notifCopy,
    },
  };
}

export function probeSentence(kind: string, language: UiLanguage = 'en'): string {
  const text = copyFor(language);
  const detail = kind === 'credentials' ? text.probeCredentials
    : kind === 'rejected' ? text.probeRejected
      : kind === 'space' ? text.probeSpace
        : kind === 'unreachable' ? text.probeUnreachable
          : kind === 'ok' ? text.probeOk
            : text.notSaved;
  if (kind === 'ok') return detail;
  return `${detail} ${text.bookmarksUnchanged}`;
}
